package ti85family

// Token codes. One-byte tokens use the byte value; two-byte tokens are
// prefix<<8 | second byte (prefixes 0x3D and 0x8E).
const (
	tokString   = 0x2D // "…" zero-terminated
	tokNameQ    = 0x32 // length-prefixed name (x, y, r, t, θ, Q1…)
	tokName1    = 0x33 // 0x33..0x3A: names of 1..8 bytes
	tokName8    = 0x3A
	tokNameY    = 0x3B // length-prefixed name (y1…, xt1…, r1…)
	tokNameStat = 0x3C // length-prefixed name (statistics results)
	tokPrefix3D = 0x3D
	tokConvert  = 0x3E // unit conversion: len,from,len,to
	tokNumber   = 0x44 // literal number, zero-terminated
	tokColon    = 0x6E
	tokNewline  = 0x6F
	tokPrefix8E = 0x8E
	tokLbl      = 0xE0 // label, zero-terminated
	tokGoto     = 0xE1 // 2 bytes (cached jump target) + label, zero-terminated

	tokAsmPrgm    = 0x8E27 // rest of program is ASCII hex
	tokAsmCompile = 0x8E28 // rest of program is Z80 machine code
	tokEditLock   = 0x8E29 // edit-lock marker at start of program
	tokExtCall    = 0x8E32 // 2 bytes + length-prefixed name (call of an external routine)
	tokRemark     = 0xFF   // zero-terminated text; used as a comment hack
)

const (
	FlagSpaceAfter = 1 << iota // statement word followed by its argument: "If X", "Disp X"
	FlagPad                    // infix word: " and ", " or "
)

